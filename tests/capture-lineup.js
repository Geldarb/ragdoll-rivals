import {chromium} from 'playwright';
import fs from 'node:fs';
import {createServer} from '../server/index.js';
const dir=process.env.SHOTS||'screenshots/local-1.4';
fs.mkdirSync(dir,{recursive:true});
const server=createServer();
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const url=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1600,height:520}});
await page.goto(url,{waitUntil:'networkidle'});
await page.setContent(`<!DOCTYPE html><html><body style="margin:0;background:#1b2421"><canvas id="c" width="1600" height="520"></canvas><script type="module">
import {drawWeapon,drawBody,drawBackdrop,drawGround} from '/art.js';
import {GEAR,DEFAULT_BUILD} from '/rules.js';
const c=document.getElementById('c').getContext('2d');
drawBackdrop(c,1600,520,450);
c.save();c.translate(0,-20);drawGround(c);c.restore();
const fighter={facing:1,build:Object.assign({},DEFAULT_BUILD,{weapon:'sword',shield:'none',helmet:'cap',armour:'leather'}),parts:{torso:{x:140,y:250,a:0},pelvis:{x:140,y:287,a:0},head:{x:140,y:196,a:0},upperArmL:{x:118,y:250,a:.15},lowerArmL:{x:112,y:285,a:.1},handL:{x:108,y:312,a:0},upperArmR:{x:162,y:250,a:-.15},lowerArmR:{x:168,y:285,a:-.1},handR:{x:172,y:312,a:0},thighL:{x:130,y:310,a:.05},shinL:{x:130,y:352,a:.02},footL:{x:132,y:373,a:0},thighR:{x:150,y:310,a:-.05},shinR:{x:150,y:352,a:-.02},footR:{x:152,y:373,a:0}},weaponOff:true};
drawBody(c,fighter);
c.fillStyle='#f2e6c4';c.font='16px Georgia,serif';c.fillText('Fighter',108,428);
const height=(fighter.parts.footR.y+5)-(fighter.parts.head.y-19);
c.fillStyle='#d5af5f';c.font='13px sans-serif';c.fillText(Math.round(height)+' px tall',105,448);
const names=Object.keys(GEAR.weapons);
names.forEach((id,i)=>{
  const x=300+i*118,y=260,r=GEAR.weapons[id].reach;
  drawWeapon(c,{x:x,y:y,a:0},id);
  c.fillStyle='#f2e6c4';c.font='13px Georgia,serif';c.textAlign='center';
  c.fillText(GEAR.weapons[id].label||id,x,428);
  c.fillStyle='#d5af5f';c.font='12px sans-serif';
  c.fillText(r+' px',x,448);
});
c.fillStyle='#f2e6c4';c.font='22px Georgia,serif';c.textAlign='left';
c.fillText('Ragdoll Rivals — weapon scale versus a fighter',40,36);
window.__done=true;
</script></body></html>`);
await page.waitForFunction(()=>window.__done,{timeout:15000});
await page.screenshot({path:dir+'/weapon-lineup.png'});
await browser.close();
await new Promise(r=>server.close(r));
console.log('wrote',dir+'/weapon-lineup.png');
